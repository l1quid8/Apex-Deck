import { chromium } from '../../node_modules/playwright/index.mjs';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const html = fs.readFileSync(new URL('../adaptive-thread-panes.html', import.meta.url), 'utf8');
const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless:true});
let checks = 0;
const check=(value,message)=>{assert.ok(value,message);checks++;};
try {
  for (const viewport of [{width:1512,height:945},{width:1100,height:650}]) {
    const page = await browser.newPage({viewport});
    const errors = []; page.on('pageerror', e => errors.push(String(e)));
    await page.setContent(html); await page.waitForTimeout(400);
    const input = page.locator('#mk-input');
    const fill=async text=>{const editor=page.locator('.mk-rich-input');await (await editor.isVisible()?editor:input).fill(text);};
    await fill('@null');
    check(await page.locator('.mk-at-picker [data-thread-id]').count()===0,'@ picker contains agents only');
    check((await page.locator('.mk-at-picker').innerText()).toLowerCase().includes('agents'),'@ opens agent picker');
    await fill('#Multiple thread');
    check(!(await page.locator('.mk-at-picker').innerText()).toLowerCase().includes('agents'),'# picker contains threads only');
    await page.locator('.mk-at-picker button').filter({hasText:'Multiple thread pane management'}).click();
    assert.equal(await page.locator('.mk-thread-tag').count(), 1, 'picker must insert a solid atomic thread tag'); checks++;
    assert.match(await input.inputValue(), /⟦thread:pane-mw7h99uz-0⟧/, 'thread tag serializes a stable ID'); checks++;
    assert.equal(await page.locator('.mk-rich-input').getAttribute('contenteditable'), 'true'); checks++;
    const rich=page.locator('.mk-rich-input');
    await page.keyboard.type('what is the status #t3 code');
    await page.locator('.mk-at-picker button[data-thread-id="pane-mv5vv0fh-0"]').click();
    await page.keyboard.type('/compact');
    let plan=await page.evaluate(()=>window._testMulti.plan());
    check(plan.plans.find(p=>p.id==='pane-mv5vv0fh-0').outgoing==='/compact','command remains its exact separate slice');
    check(plan.plans.find(p=>p.id==='pane-mw7h99uz-0').outgoing==='what is the status','picker replaces its query without leftover @ text');
    await page.locator('.mk-to-count').click();
    const rows=page.locator('.mk-multi-row');
    check((await rows.count())===2,'every destination has a preview row');
    check(await rows.filter({hasText:'t3 code'}).locator('.mk-mr-agent-btn').innerText()==='→ /compact (command)','preview shows exact command');
    const normal=rows.filter({hasText:'Multiple thread pane management'});
    await normal.locator('.mk-mr-agent-btn').click();
    const agentLabels=await page.locator('.mk-agent-menu .label').allTextContents();
    check(agentLabels.includes('Null')&&!agentLabels.includes('Muck'),'dropdown restricts choices to thread members');
    await page.locator('.mk-agent-menu button').filter({hasText:'Null'}).click();
    check((await normal.innerText()).includes('instead of'),'per-send replacement remains visible');
    await rich.click(); await page.keyboard.press('End'); await page.keyboard.type(' #Multiple thread');
    check(await page.locator('.mk-at-picker button[data-thread-id="pane-mw7h99uz-0"]').isDisabled(),'tagged row blocks duplicate picking');
    // Corrupt/pasted tags still hit the parser's duplicate blocker.
    await page.evaluate(()=>{const input=document.querySelector('#mk-input');input.value='⟦thread:pane-mw7h99uz-0⟧ first ⟦thread:pane-mw7h99uz-0⟧ duplicate';input.dispatchEvent(new Event('input',{bubbles:true}));});
    check(await page.locator('.mk-thread-tag.mk-bad').count()===2,'both duplicate tags are highlighted');
    check(await page.locator('.round-send').isDisabled(),'duplicate tags block Send');
    // Replace the entire draft through real editor typing, then pick destinations again.
    await rich.fill('#Multiple thread');
    await page.locator('.mk-at-picker button[data-thread-id="pane-mw7h99uz-0"]').click();
    await page.keyboard.type('@null '+ 'full preview '.repeat(25)+' #t3 code');
    await page.locator('.mk-at-picker button[data-thread-id="pane-mv5vv0fh-0"]').click();
    await page.keyboard.type('/compact');
    plan=await page.evaluate(()=>window._testMulti.plan());
    check(plan.plans.find(p=>p.id==='pane-mv5vv0fh-0').outgoing==='/compact','shared prose never prepends to command');
    const outgoing=plan.plans.find(p=>p.id==='pane-mw7h99uz-0').outgoing;
    check(outgoing.startsWith('@null'),'ordinary slice preserves its exact text');
    await page.locator('.mk-to-count').click();
    check(await normal.locator('.mk-slice-text').count()===0,'compact review omits repeated prose');
    check((await input.inputValue()).includes('full preview '.repeat(25).trim()),'composer retains full text beyond 180 characters');
    // Place a visible file reference in the message slice, then test command protection.
    await rich.click(); await rich.press('Meta+a'); await rich.press('ArrowLeft');
    await page.keyboard.press('ArrowRight');
    await page.locator('#mk-shared .composer-plus').click();
    const withFile=await input.inputValue();const file=withFile.match(/⟦file:[^⟧]+⟧/)[0];
    const clean=withFile.replace(file,'');
    await rich.fill(clean.replace('⟦thread:pane-mv5vv0fh-0⟧',file+' ⟦thread:pane-mv5vv0fh-0⟧'));
    check(await normal.locator('.mk-att-dest').getAttribute('title')==='file-1.png','destination review names inline attachment');
    check(!(await rows.filter({hasText:'t3 code'}).innerText()).includes('file-1.png'),'attachment does not leak into other slice');
    const assigned=await input.inputValue();
    await rich.fill(assigned+' '+file);
    check(await page.locator('.round-send').isDisabled(),'command slices cannot silently receive attachments');
    await rich.fill(assigned);
    await page.screenshot({path:`/tmp/null-routing-preview-${viewport.width}.png`});
    await page.locator('.mk-fail-demo input').check();
    await page.locator('.round-send').click();
    check((await input.inputValue()).length>0,'failure preserves original draft');
    check(await page.locator('.mk-retry').isEnabled(),'failed slice offers retry');
    const sentBefore=await page.evaluate(()=>JSON.stringify(window._testMulti.state().sent.find(([id])=>id==='pane-mw7h99uz-0')));
    await page.locator('.mk-retry').click();
    check(await input.inputValue()==='','successful retry clears sent draft');
    check(await page.evaluate(()=>JSON.stringify(window._testMulti.state().sent.find(([id])=>id==='pane-mw7h99uz-0')))===sentBefore,'retry never duplicates successful slice');
    check((await page.locator('.mk-multi-hint').allTextContents()).filter(t=>t.startsWith('✓')).length===2,'both slices report successful mock delivery');
    await page.screenshot({path:`/tmp/null-routing-${viewport.width}.png`});
    // Empty selected destinations and unresolved tags are hard blockers.
    await fill('⟦thread:pane-mw7h99uz-0⟧ @null only here');
    check(!(await page.locator('.round-send').isDisabled()),'deleting destination tags removes destinations from this send');
    await rich.click(); await page.keyboard.press('Meta+a'); await page.keyboard.type('⟦thread:missing-id⟧ text');
    check(await page.locator('.round-send').isDisabled(),'unresolved stable tag blocks Send');
    await rich.fill('⟦thread:pane-mw7h99uz-0⟧ okay ⟦thread:pane-mv5vv0fh-0⟧ /plan');
    check(await page.locator('.round-send').isDisabled(),'unsupported commands require their separate UI');
    // Reset to test a tag pointing at the currently focused single destination.
    await page.locator('#mk-reset').click();
    await fill('#Multiple thread');
    await page.locator('.mk-at-picker button[data-thread-id="pane-mw7h99uz-0"]').click();
    await page.keyboard.type('one thread slice');
    check(await rich.isVisible(),'tagging the current thread still uses the atomic editor');
    check((await page.evaluate(()=>window._testMulti.plan())).plans.length===1,'one tagged destination has one payload');
    // Native Backspace removes the entire noneditable chip as one unit.
    await rich.click(); await page.keyboard.press('Meta+ArrowLeft'); await page.keyboard.press('ArrowRight'); await page.keyboard.press('Backspace');
    check(!(await input.inputValue()).includes('⟦thread:'),'Backspace never leaves a partial thread ID');
    // Renaming or colliding titles cannot change serialized routing identity.
    const stable=await page.evaluate(()=>{
      const a=window.THREAD_SNAPSHOT.threads.find(t=>t.id==='pane-mw7h99uz-0');
      const b=window.THREAD_SNAPSHOT.threads.find(t=>t.id==='pane-mv5vv0fh-0');
      a.title=b.title='Same title';
      return window._testMulti.parse('⟦thread:'+a.id+'⟧ first ⟦thread:'+b.id+'⟧ second').slices.map(s=>s.threadId);
    });
    check(stable.join(',')==='pane-mw7h99uz-0,pane-mv5vv0fh-0','duplicate titles and renames retain distinct routing IDs');
    await page.locator('#mk-reset').click();
    await page.evaluate(()=>window._testMulti.toggle('pane-mv5vv0fh-0'));
    await fill('⟦thread:pane-mw7h99uz-0⟧ ⟦thread:pane-mv5vv0fh-0⟧ @null do A @jigga do B @null answer');
    check((await page.evaluate(()=>window._testMulti.plan())).plans.every(p=>p.rec.agent==='Null'),'last repeated mention determines recipient');
    await fill('⟦thread:pane-mw7h99uz-0⟧ ⟦thread:pane-mv5vv0fh-0⟧ @jigga hello');
    await page.locator('.round-send').click();
    await fill('⟦thread:pane-mw7h99uz-0⟧ ⟦thread:pane-mv5vv0fh-0⟧ next request');
    check((await page.evaluate(()=>window._testMulti.plan())).plans.every(p=>p.rec.agent==='Jigga'),'new sends update last-mention defaults');
    if(await page.locator('.mk-to-count').getAttribute('aria-expanded')==='false')await page.locator('.mk-to-count').click();
    await page.locator('.mk-multi-row').first().locator('.mk-mr-agent-btn').click();
    await page.locator('.mk-agent-menu button').filter({hasText:'Null'}).click();
    await page.locator('.round-send').click();
    await fill('⟦thread:pane-mw7h99uz-0⟧ ⟦thread:pane-mv5vv0fh-0⟧ follow up');
    check((await page.evaluate(()=>window._testMulti.plan())).plans.every(p=>p.rec.agent==='Jigga'),'per-send override does not change default');
    await page.locator('.mk-fail-demo input').check();
    await page.locator('.round-send').click();
    await page.keyboard.press('Escape');
    await fill('brand new unsent prose #Same title');
    await page.locator('.mk-at-picker button[data-thread-id="pane-mw7h99uz-0"]').click();
    check((await page.evaluate(()=>window._testMulti.state())).draft.endsWith('follow up'),'new thread pick cannot overwrite a pending batch');
    check(await page.locator('.mk-pending').isVisible(),'failed payload remains reachable outside multi-selection');
    await page.locator('.mk-retry').click();
    check(await input.inputValue()==='brand new unsent prose #Same title','retry preserves unrelated single-thread draft');
    await page.locator('#mk-reset').click();
    await page.evaluate(()=>{window._testMulti.toggle('pane-mv5vv0fh-0');window._testMulti.toggle('pane-mvyq6vew-0');});
    await fill('⟦thread:pane-mw7h99uz-0⟧ first ⟦thread:pane-mv5vv0fh-0⟧ second');
    await page.locator('.mk-to-count').click();
    await page.locator('.mk-multi-row').filter({has:page.locator('button[aria-label="Remove Same title from this message"]')}).first().locator('.mk-mr-x').click();
    check(!(await page.evaluate(()=>window._testMulti.plan())).ids.includes('pane-mw7h99uz-0'),'removing tagged destination removes its tag and payload');
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'routing UI does not overflow viewport horizontally');
    await page.close();
    assert.deepEqual(errors, []); checks++;
  }
  console.log(`${checks}/${checks} PASS`);
} finally { await browser.close(); }
