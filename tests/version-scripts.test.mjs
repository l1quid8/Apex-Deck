import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const CHECK = join(process.cwd(), 'scripts/check-versions.mjs');
const BUMP = join(process.cwd(), 'scripts/bump-version.mjs');

const lockBlock = (name, version, extra = '') => `[[package]]\nname = "${name}"\nversion = "${version}"\n${extra}\n`;

/** A tiny repo with every file the real one keeps a version in. */
function fixture(v, { irohLock = v, npmPlatform = v } = {}) {
  const dir = mkdtempSync(join(tmpdir(), 'apex-versions-'));
  const w = (p, text) => { mkdirSync(join(dir, p, '..'), { recursive: true }); writeFileSync(join(dir, p), text); };
  w('Cargo.toml', `[workspace]\nresolver = "2"\nmembers = ["crates/apex-core", "crates/apex-pairing", "crates/apex-ipc-check"]\n\n[workspace.package]\nversion = "${v}"\nedition = "2021"\n\n[workspace.dependencies]\nserde = { version = "1", features = ["derive"] }\n`);
  w('crates/apex-core/Cargo.toml', `[package]\nname = "apex-core"\nversion.workspace = true\nedition.workspace = true\n`);
  w('crates/apex-pairing/Cargo.toml', `[package]\nname = "apex-pairing"\nversion.workspace = true\n`);
  w('crates/apex-ipc-check/Cargo.toml', `[package]\nname = "apex-ipc-check"\nversion.workspace = true\n`);
  w('crates/iroh-mobile/Cargo.toml', `[package]\nname = "apex-iroh-mobile"\nversion = "0.0.0"\n\n[workspace]\n`);
  w('Cargo.lock', `# This file is automatically @generated by Cargo.\nversion = 4\n\n${lockBlock('apex-core', v, 'dependencies = [\n "serde",\n]')}${lockBlock('apex-iroh-mobile', '0.0.0')}${lockBlock('apex-pairing', v)}${lockBlock('serde', '1.0.219', 'source = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "abc"')}`);
  w('crates/iroh-mobile/Cargo.lock', `# This file is automatically @generated by Cargo.\nversion = 4\n\n${lockBlock('apex-iroh-mobile', '0.0.0')}${lockBlock('apex-pairing', irohLock)}${lockBlock('serde', '1.0.219', 'source = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "abc"')}`);
  w('package.json', `{\n  "name": "apex-deck",\n  "private": true,\n  "version": "${v}",\n  "type": "module",\n  "dependencies": {\n    "react": "^19.3.0"\n  }\n}\n`);
  w('package-lock.json', `{\n  "name": "apex-deck",\n  "version": "${v}",\n  "lockfileVersion": 3,\n  "requires": true,\n  "packages": {\n    "": {\n      "name": "apex-deck",\n      "version": "${v}",\n      "dependencies": {\n        "react": "^19.3.0"\n      }\n    },\n    "node_modules/react": {\n      "version": "19.3.0"\n    }\n  }\n}\n`);
  w('npm/cli/package.json', `{\n  "name": "@apex-deck/cli",\n  "version": "${v}",\n  "bin": {\n    "apex": "bin/apex"\n  },\n  "optionalDependencies": {\n    "@apex-deck/cli-darwin-arm64": "${npmPlatform}",\n    "@apex-deck/cli-linux-x64": "${npmPlatform}"\n  }\n}\n`);
  w('npm/cli-darwin-arm64/package.json', `{\n  "name": "@apex-deck/cli-darwin-arm64",\n  "version": "${npmPlatform}",\n  "os": [\n    "darwin"\n  ]\n}\n`);
  w('npm/cli-linux-x64/package.json', `{\n  "name": "@apex-deck/cli-linux-x64",\n  "version": "${npmPlatform}",\n  "os": [\n    "linux"\n  ]\n}\n`);
  return dir;
}

const run = (script, args, cwd) => spawnSync(process.execPath, [script, '--root', cwd, ...args], { encoding: 'utf8' });
const read = (dir, p) => readFileSync(join(dir, p), 'utf8');

test('check passes when every manifest and lockfile agree', () => {
  const dir = fixture('0.9.16');
  try {
    const r = run(CHECK, [], dir);
    assert.equal(r.status, 0, r.stderr + r.stdout);
    assert.match(r.stdout, /0\.9\.16/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('check fails and names the file that disagrees', () => {
  const dir = fixture('0.9.16', { irohLock: '0.9.15' });
  try {
    const r = run(CHECK, [], dir);
    assert.equal(r.status, 1);
    assert.match(r.stderr, /crates\/iroh-mobile\/Cargo\.lock/);
    assert.match(r.stderr, /apex-pairing/);
    assert.match(r.stderr, /0\.9\.15/);
    assert.match(r.stderr, /bump-version/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('check fails when the npm platform packages lag the workspace', () => {
  const dir = fixture('0.9.16', { npmPlatform: '0.9.14' });
  try {
    const r = run(CHECK, [], dir);
    assert.equal(r.status, 1);
    assert.match(r.stderr, /npm\/cli\/package\.json/);
    assert.match(r.stderr, /npm\/cli-linux-x64\/package\.json/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('check can be told which version to expect', () => {
  const dir = fixture('0.9.16');
  try {
    assert.equal(run(CHECK, ['--expect', '0.9.16'], dir).status, 0);
    const r = run(CHECK, ['--expect', '0.9.17'], dir);
    assert.equal(r.status, 1);
    assert.match(r.stderr, /0\.9\.17/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('bump rewrites every version site and nothing else, then the check passes', () => {
  const dir = fixture('0.9.16', { irohLock: '0.9.15' });
  try {
    const before = Object.fromEntries(['Cargo.toml', 'Cargo.lock', 'crates/iroh-mobile/Cargo.lock', 'package.json', 'package-lock.json', 'npm/cli/package.json', 'npm/cli-darwin-arm64/package.json', 'npm/cli-linux-x64/package.json'].map(p => [p, read(dir, p)]));
    const r = run(BUMP, ['0.9.17'], dir);
    assert.equal(r.status, 0, r.stderr + r.stdout);
    for (const p of Object.keys(before)) {
      const after = read(dir, p);
      assert.ok(!after.includes('0.9.16') && !after.includes('0.9.15'), `${p} still carries an old version:\n${after}`);
      // Only version strings change: the same text once versions are blanked out.
      assert.equal(after.replaceAll('0.9.17', 'V'), before[p].replaceAll('0.9.16', 'V').replaceAll('0.9.15', 'V'), p);
      assert.match(r.stdout, new RegExp(p.replace(/[.\/]/g, '\\$&')));
    }
    assert.match(read(dir, 'Cargo.lock'), /name = "serde"\nversion = "1\.0\.219"/);
    assert.match(read(dir, 'Cargo.lock'), /name = "apex-iroh-mobile"\nversion = "0\.0\.0"/);
    assert.match(read(dir, 'crates/iroh-mobile/Cargo.lock'), /name = "apex-pairing"\nversion = "0\.9\.17"/);
    const lock = JSON.parse(read(dir, 'package-lock.json'));
    assert.equal(lock.version, '0.9.17');
    assert.equal(lock.packages[''].version, '0.9.17');
    assert.equal(lock.packages['node_modules/react'].version, '19.3.0');
    const cli = JSON.parse(read(dir, 'npm/cli/package.json'));
    assert.equal(cli.optionalDependencies['@apex-deck/cli-darwin-arm64'], '0.9.17');
    assert.equal(Object.keys(JSON.parse(read(dir, 'package.json'))).join(','), 'name,private,version,type,dependencies');
    assert.equal(run(CHECK, [], dir).status, 0);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('bump refuses a version that is not x.y.z and changes nothing', () => {
  const dir = fixture('0.9.16');
  try {
    const before = read(dir, 'Cargo.toml');
    for (const bad of ['v0.9.17', '0.9', '0.9.17 ', 'latest']) {
      const r = run(BUMP, [bad], dir);
      assert.equal(r.status, 1, bad);
      assert.match(r.stderr, /x\.y\.z/);
    }
    assert.equal(run(BUMP, [], dir).status, 1);
    assert.equal(read(dir, 'Cargo.toml'), before);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('bump --dry-run reports the plan without writing', () => {
  const dir = fixture('0.9.16');
  try {
    const r = run(BUMP, ['0.9.17', '--dry-run'], dir);
    assert.equal(r.status, 0, r.stderr);
    assert.match(r.stdout, /Cargo\.toml/);
    assert.match(read(dir, 'Cargo.toml'), /version = "0\.9\.16"/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('bump refuses to go backwards unless told to', () => {
  const dir = fixture('0.9.16');
  try {
    const r = run(BUMP, ['0.9.15'], dir);
    assert.equal(r.status, 1);
    assert.match(r.stderr, /--allow-downgrade/);
    assert.equal(run(BUMP, ['0.9.15', '--allow-downgrade'], dir).status, 0);
    assert.match(read(dir, 'Cargo.toml'), /version = "0\.9\.15"/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('the real repository reads cleanly (agreement is CI\'s job, not this test\'s)', () => {
  // Another checkout state may legitimately disagree mid-bump; only the reader must not crash.
  const r = run(CHECK, [], process.cwd());
  assert.ok(r.status === 0 || r.status === 1, r.stderr);
  assert.match(r.stdout + r.stderr, /Cargo\.toml/);
});
